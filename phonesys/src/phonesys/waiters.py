"""Bridging ARI's "operation started" REST replies to "operation finished" events.

Several ARI operations return 201 as soon as the operation *begins* and report
completion only later, over the event WebSocket. Anything that must not run
until the operation actually finishes has to wait for that event, keyed by an
id the caller chooses *before* issuing the REST call -- otherwise the event can
land before the waiter is registered and be dropped.
"""
from __future__ import annotations

import asyncio
import logging

logger = logging.getLogger(__name__)


class EventWaiter:
    """Maps a caller-chosen id to a future resolved by an ARI event."""

    def __init__(self) -> None:
        self._waiters: dict[str, asyncio.Future] = {}

    def expect(self, key: str) -> asyncio.Future:
        """Register interest before starting the operation."""
        fut = asyncio.get_running_loop().create_future()
        self._waiters[key] = fut
        return fut

    def resolve(self, key: str, ok: bool = True) -> None:
        """Called from the event loop when the completion event arrives.

        Unknown keys are ignored: events arrive for every operation on the
        system, not only the ones this process started.
        """
        fut = self._waiters.pop(key, None)
        if fut is not None and not fut.done():
            fut.set_result(ok)

    def discard(self, key: str) -> None:
        """Give up (timeout, or the call ended)."""
        fut = self._waiters.pop(key, None)
        if fut is not None and not fut.done():
            fut.cancel()


class PlaybackWaiter(EventWaiter):
    """Waits for PlaybackFinished.

    POST /channels/{id}/play returns 201 when playback STARTS. Returning from
    _speak() at that point puts the turn loop's recorder on the line while the
    caller is still listening to the agent, and the caller's silence during
    playback is then charged as a silent turn.

    The playbackId is generated by the bridge and passed to ARI, so the waiter
    can be registered before the REST call and a short prompt cannot finish
    before anyone is listening for it.
    """


class DtmfCollector:
    """Collect keypad digits from ARI ChannelDtmfReceived events.

    Only channels actively waiting for a PIN get a queue. Digits are never
    logged or retained after the attempt ends.
    """

    def __init__(self) -> None:
        self._queues: dict[str, asyncio.Queue[str]] = {}

    def feed(self, channel_id: str, digit: str) -> None:
        queue = self._queues.get(channel_id)
        if queue is not None and digit in "0123456789":
            queue.put_nowait(digit)

    async def collect(self, channel_id: str, length: int,
                      timeout: float = 12.0) -> str | None:
        queue: asyncio.Queue[str] = asyncio.Queue()
        self._queues[channel_id] = queue
        digits: list[str] = []
        try:
            async with asyncio.timeout(timeout):
                while len(digits) < length:
                    digits.append(await queue.get())
            return "".join(digits)
        except TimeoutError:
            return None
        finally:
            self._queues.pop(channel_id, None)
